def process_single_lead(
    lead: Lead,
    templates: Dict[str, List[Template]],
    output_folder: Path,
    claude_client: anthropic.Anthropic,
    image_sourcer: ImageSourcer,
    excel_path: Path,
    port: int = DEFAULT_PORT,
    excel_lock: Optional[Lock] = None
) -> ProcessingResult:
    """
    Full processing pipeline for a single lead.

    Args:
        port: Port number for Astro server (default 4321)
        excel_lock: Thread lock for Excel writes (optional, for parallel processing)
    """
    logger.info(f"{'='*60}")
    logger.info(f"Processing: {lead.business_name} (port {port})")
    logger.info(f"{'='*60}")

    # Create output directory
    comuna_folder = sanitize_folder_name(lead.comuna) or 'Sin_Comuna'
    business_folder = sanitize_folder_name(lead.business_name)
    output_dir = output_folder / comuna_folder / business_folder

    def safe_update_excel(row_index: int, status: str, mockup_path: Optional[str] = None, mockup_date: Optional[datetime] = None):
        """Thread-safe Excel update."""
        if excel_lock:
            with excel_lock:
                update_lead_status(excel_path, row_index, status, mockup_path, mockup_date)
        else:
            update_lead_status(excel_path, row_index, status, mockup_path, mockup_date)

    try:
        # 1. Update Excel to Processing
        safe_update_excel(lead.row_index, 'Processing')

        # 2. Get templates for niche
        niche_templates = templates.get(lead.niche, [])
        if not niche_templates:
            # Try to find any available templates
            for niche, tmpl_list in templates.items():
                if tmpl_list:
                    niche_templates = tmpl_list
                    logger.warning(f"No templates for niche '{lead.niche}', using '{niche}'")
                    break

        if not niche_templates:
            raise ValueError("No templates available")

        # 3. Get design decisions from Claude
        logger.info("Getting design decisions from Claude...")
        design_decisions = choose_design_decisions(
            claude_client,
            lead,
            niche_templates
        )
        logger.info(f"Design: template={design_decisions.template_name}, theme={design_decisions.theme}")

        # 4. Source images
        logger.info("Sourcing images...")
        output_dir.mkdir(parents=True, exist_ok=True)
        images = image_sourcer.source_images_for_lead(lead, output_dir)
        logger.info(f"Sourced {len(images)} images")

        # 5. Generate content with Claude
        logger.info("Generating personalized content...")
        content = generate_personalized_content(
            claude_client,
            lead,
            design_decisions
        )

        # 6. Find selected template
        selected_template = next(
            (t for t in niche_templates if t.name == design_decisions.template_name),
            niche_templates[0]
        )

        # 7. Copy template
        logger.info(f"Copying template {selected_template.name}...")
        proyecto_dir = copy_template_to_output(selected_template, output_dir)

        # 8. Generate and write site.config.ts
        logger.info("Generating site.config.ts...")
        config_content = generate_site_config_content(
            content, design_decisions, lead, images
        )
        write_site_config(proyecto_dir, config_content)

        # 9. Modify index.astro
        logger.info("Modifying index.astro...")
        modify_index_astro(
            proyecto_dir,
            design_decisions.sections_order,
            design_decisions.sections_to_hide
        )

        # 10. Copy images to public
        logger.info("Copying images to public folder...")
        copy_images_to_public(proyecto_dir, images)

        # 11-15. Build and screenshot
        with AstroServerManager(proyecto_dir, port=port) as server:
            # 11. npm install
            logger.info("Installing dependencies...")
            if not server.install_dependencies():
                raise RuntimeError("npm install failed")

            # 12. Start server
            logger.info("Starting Astro server...")
            if not server.start_server():
                raise RuntimeError("Failed to start Astro server")

            # 13-14. Take screenshot
            logger.info("Taking screenshot...")
            mockup_path = output_dir / 'mockup.png'
            screenshot_success = asyncio.run(
                take_screenshot(
                    f"http://localhost:{server.port}",
                    mockup_path
                )
            )

            if not screenshot_success:
                raise RuntimeError("Screenshot failed")

        # 16. Generate outreach messages
        logger.info("Generating outreach messages...")
        messages = generate_outreach_messages(
            claude_client,
            lead,
            'mockup.png'
        )

        # 17. Save outputs
        save_outreach_messages(output_dir, messages)
        save_metadata(output_dir, lead, design_decisions, content, images)

        # 18. Update Excel to Completed
        safe_update_excel(
            lead.row_index,
            'Completed',
            str(output_dir),
            datetime.now()
        )

        logger.info(f"Successfully processed: {lead.business_name}")

        return ProcessingResult(
            success=True,
            lead=lead,
            output_path=output_dir
        )

    except Exception as e:
        logger.error(f"Failed to process {lead.business_name}: {e}")

        # Update Excel with failure
        safe_update_excel(
            lead.row_index,
            f'Failed: {str(e)[:100]}'
        )

        return ProcessingResult(
            success=False,
            lead=lead,
            error_message=str(e)
        )


def print_summary(results: List[ProcessingResult]):
    """Prints processing summary."""
    successful = [r for r in results if r.success]
    failed = [r for r in results if not r.success]

    print("\n" + "="*60)
    print("RESUMEN DE PROCESAMIENTO")
    print("="*60)
    print(f"Total procesados: {len(results)}")
    print(f"Exitosos: {len(successful)}")
    print(f"Fallidos: {len(failed)}")

    if successful:
        print("\n✅ Exitosos:")
        for r in successful:
            print(f"  - {r.lead.business_name}: {r.output_path}")

    if failed:
        print("\n❌ Fallidos:")
        for r in failed:
            print(f"  - {r.lead.business_name}: {r.error_message}")

    print("="*60)


