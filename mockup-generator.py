def sanitize_folder_name(name: str) -> str:
    """
    Converts a string to a safe folder name.
    """
    # Normalize unicode characters
    name = unicodedata.normalize('NFKD', name)
    name = name.encode('ASCII', 'ignore').decode('ASCII')

    # Replace spaces and special chars with underscores
    name = re.sub(r'[^\w\s-]', '', name)
    name = re.sub(r'[-\s]+', '_', name)

    # Remove leading/trailing underscores
    name = name.strip('_')

    return name or 'business'


def copy_template_to_output(
    template: Template,
    output_dir: Path
) -> Path:
    """
    Copies template to output directory.
    Skips node_modules if present.
    """
    proyecto_dir = output_dir / 'proyecto'

    def ignore_patterns(directory, files):
        """Returns files to ignore during copy."""
        ignore = []
        if 'node_modules' in files:
            ignore.append('node_modules')
        if '.git' in files:
            ignore.append('.git')
        return ignore

    if proyecto_dir.exists():
        shutil.rmtree(proyecto_dir)

    shutil.copytree(
        template.path,
        proyecto_dir,
        ignore=ignore_patterns
    )

    return proyecto_dir


