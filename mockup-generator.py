class ParallelProcessor:
    """
    Handles parallel processing of multiple leads with thread-safe operations.
    Each worker gets a unique port for its Astro server.
    """

    def __init__(self, max_workers: int = DEFAULT_WORKERS):
        self.max_workers = min(max_workers, MAX_WORKERS)
        self.executor = ThreadPoolExecutor(max_workers=self.max_workers)
        self.port_pool: Queue = Queue()
        self.excel_lock = Lock()
        self.api_semaphore = Semaphore(5)  # Rate limiting for API calls

        # Initialize port pool
        for port in PORT_POOL[:self.max_workers]:
            self.port_pool.put(port)

        logger.info(f"ParallelProcessor initialized with {self.max_workers} workers")

    def process_leads_parallel(
        self,
        leads: List[Lead],
        templates: Dict[str, List[Template]],
        output_folder: Path,
        claude_client: anthropic.Anthropic,
        excel_path: Path
    ) -> List[ProcessingResult]:
        """
        Processes multiple leads in parallel using thread pool.
        Returns list of ProcessingResults.
        """
        results: List[ProcessingResult] = []
        futures = []

        # Submit all leads to the executor
        for lead in leads:
            future = self.executor.submit(
                self._process_lead_worker,
                lead,
                templates,
                output_folder,
                claude_client,
                excel_path
            )
            futures.append((future, lead))

        # Collect results with progress bar
        with tqdm(total=len(leads), desc="Procesando leads", unit="lead") as pbar:
            for future, lead in futures:
                try:
                    result = future.result()
                    results.append(result)
                    status = "✓" if result.success else "✗"
                    pbar.set_postfix_str(f"{status} {lead.business_name[:20]}")
                except Exception as e:
                    logger.error(f"Worker failed for {lead.business_name}: {e}")
                    results.append(ProcessingResult(
                        success=False,
                        lead=lead,
                        error_message=str(e)
                    ))
                finally:
                    pbar.update(1)

        return results

    def _process_lead_worker(
        self,
        lead: Lead,
        templates: Dict[str, List[Template]],
        output_folder: Path,
        claude_client: anthropic.Anthropic,
        excel_path: Path
    ) -> ProcessingResult:
        """
        Worker function that processes a single lead.
        Acquires a port from the pool and releases it when done.
        """
        port = self.port_pool.get()  # Blocks until a port is available
        try:
            # Create a dedicated image sourcer for this worker
            image_sourcer = ImageSourcer(
                fallback_folder=Path(__file__).parent / 'fallback_images'
            )

            try:
                result = process_single_lead(
                    lead=lead,
                    templates=templates,
                    output_folder=output_folder,
                    claude_client=claude_client,
                    image_sourcer=image_sourcer,
                    excel_path=excel_path,
                    port=port,
                    excel_lock=self.excel_lock
                )
            finally:
                image_sourcer.close()

            return result
        finally:
            self.port_pool.put(port)  # Return port to pool

    def shutdown(self):
        """Cleans up the executor."""
        self.executor.shutdown(wait=True)
        logger.info("ParallelProcessor shutdown complete")


