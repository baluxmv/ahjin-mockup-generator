class RateLimiter:
    """Simple rate limiter for API calls."""

    def __init__(self):
        self.last_call_times: Dict[str, float] = {}

    def wait_if_needed(self, service: str):
        """Blocks until rate limit allows next request."""
        delay = RATE_LIMITS.get(service, 1.0)
        last_call = self.last_call_times.get(service, 0)
        elapsed = time.time() - last_call

        if elapsed < delay:
            time.sleep(delay - elapsed)

        self.last_call_times[service] = time.time()


class ImageSourcer:
    """Handles image sourcing with fallback chain."""

    def __init__(
        self,
        unsplash_key: Optional[str] = None,
        fallback_folder: Optional[Path] = None
    ):
        self.unsplash_key = unsplash_key or os.getenv('UNSPLASH_ACCESS_KEY')
        self.fallback_folder = fallback_folder or Path(__file__).parent / 'fallback_images'
        self.rate_limiter = RateLimiter()
        self.session = httpx.Client(timeout=30.0, follow_redirects=True)
        self._instaloader: Optional[instaloader.Instaloader] = None

    @property
    def instaloader(self) -> instaloader.Instaloader:
        """Lazy-load instaloader instance."""
        if self._instaloader is None:
            self._instaloader = instaloader.Instaloader(
                download_videos=False,
                download_video_thumbnails=False,
                download_geotags=False,
                download_comments=False,
                save_metadata=False,
                compress_json=False,
                quiet=True
            )
        return self._instaloader

    def source_images_for_lead(
        self,
        lead: Lead,
        output_dir: Path,
        count: int = 6
    ) -> List[ImageSource]:
        """
        Attempts to source images in priority order.
        Returns list of ImageSource with local paths.
        """
        images: List[ImageSource] = []

        # Ensure output directory exists
        images_dir = output_dir / 'images'
        images_dir.mkdir(parents=True, exist_ok=True)

        # 1. Try Instagram
        if lead.instagram_fb_link:
            logger.info(f"Attempting Instagram scrape for {lead.business_name}")
            try:
                instagram_images = self.scrape_instagram(
                    lead.instagram_fb_link,
                    images_dir,
                    count
                )
                images.extend(instagram_images)
                logger.info(f"Got {len(instagram_images)} images from Instagram")
            except Exception as e:
                logger.warning(f"Instagram scraping failed: {e}")

        # 2. Try Unsplash if we need more images
        remaining = count - len(images)
        if remaining > 0 and self.unsplash_key:
            logger.info(f"Fetching {remaining} images from Unsplash")
            try:
                unsplash_images = self.fetch_unsplash_images(
                    lead.niche,
                    images_dir,
                    remaining,
                    offset=len(images)
                )
                images.extend(unsplash_images)
            except Exception as e:
                logger.warning(f"Unsplash fetch failed: {e}")

        # 3. Use placeholders for any remaining
        remaining = count - len(images)
        if remaining > 0:
            logger.info(f"Using {remaining} placeholder images")
            placeholder_images = self.get_placeholder_images(
                lead.niche,
                images_dir,
                remaining,
                offset=len(images)
            )
            images.extend(placeholder_images)

        return images

    def scrape_instagram(
        self,
        instagram_url: str,
        output_dir: Path,
        count: int = 6
    ) -> List[ImageSource]:
        """
        Scrapes recent posts from Instagram profile.
        """
        images: List[ImageSource] = []

        # Extract username from URL
        username = self._extract_instagram_username(instagram_url)
        if not username:
            logger.warning(f"Could not extract username from: {instagram_url}")
            return images

        try:
            self.rate_limiter.wait_if_needed('instagram')
            profile = instaloader.Profile.from_username(
                self.instaloader.context,
                username
            )

            if profile.is_private:
                logger.warning(f"Instagram profile @{username} is private")
                return images

            # Download posts
            for i, post in enumerate(profile.get_posts()):
                if i >= count:
                    break

                try:
                    self.rate_limiter.wait_if_needed('instagram')

                    # Get image URL
                    image_url = post.url

                    # Download image
                    response = self.session.get(image_url)
                    response.raise_for_status()

                    # Save image
                    filename = f"instagram_{i + 1}.jpg"
                    filepath = output_dir / filename

                    with open(filepath, 'wb') as f:
                        f.write(response.content)

                    # Convert to JPG if needed and resize
                    self._process_image(filepath)

                    images.append(ImageSource(
                        url=image_url,
                        local_path=filepath,
                        source_type='instagram',
                        alt_text=post.caption[:50] if post.caption else f"Instagram post {i + 1}"
                    ))

                except Exception as e:
                    logger.warning(f"Failed to download Instagram post {i}: {e}")
                    continue

        except instaloader.exceptions.ProfileNotExistsException:
            logger.warning(f"Instagram profile @{username} does not exist")
        except instaloader.exceptions.ConnectionException as e:
            logger.warning(f"Instagram connection error: {e}")
        except Exception as e:
            logger.warning(f"Instagram scraping error: {e}")

        return images

    def fetch_unsplash_images(
        self,
        query: str,
        output_dir: Path,
        count: int = 6,
        offset: int = 0
    ) -> List[ImageSource]:
        """
        Fetches images from Unsplash API.
        """
        images: List[ImageSource] = []

        if not self.unsplash_key:
            return images

        # Map niche to search query
        query_map = {
            'manicuristas': 'nail art manicure nails',
            'profesionales-salud': 'healthcare medical clinic',
        }
        search_query = query_map.get(query, query)

        try:
            self.rate_limiter.wait_if_needed('unsplash')

            response = self.session.get(
                'https://api.unsplash.com/search/photos',
                params={
                    'query': search_query,
                    'per_page': count,
                    'orientation': 'landscape'
                },
                headers={
                    'Authorization': f'Client-ID {self.unsplash_key}'
                }
            )
            response.raise_for_status()

            data = response.json()

            for i, photo in enumerate(data.get('results', [])):
                try:
                    # Get regular size URL
                    image_url = photo['urls']['regular']

                    # Download
                    img_response = self.session.get(image_url)
                    img_response.raise_for_status()

                    filename = f"unsplash_{offset + i + 1}.jpg"
                    filepath = output_dir / filename

                    with open(filepath, 'wb') as f:
                        f.write(img_response.content)

                    self._process_image(filepath)

                    images.append(ImageSource(
                        url=image_url,
                        local_path=filepath,
                        source_type='unsplash',
                        alt_text=photo.get('alt_description', f'Image {offset + i + 1}')
                    ))

                except Exception as e:
                    logger.warning(f"Failed to download Unsplash image: {e}")
                    continue

        except Exception as e:
            logger.warning(f"Unsplash API error: {e}")

        return images

    def get_placeholder_images(
        self,
        niche: str,
        output_dir: Path,
        count: int = 6,
        offset: int = 0
    ) -> List[ImageSource]:
        """
        Copies placeholder images from fallback folder.
        """
        images: List[ImageSource] = []

        # Look for niche-specific placeholders
        niche_folder = self.fallback_folder / niche

        if not niche_folder.exists():
            # Try generic folder
            niche_folder = self.fallback_folder / 'generic'

        if not niche_folder.exists():
            logger.warning(f"No fallback images found for niche: {niche}")
            return images

        # Get available images
        available_images = list(niche_folder.glob('*.jpg')) + list(niche_folder.glob('*.png'))

        for i in range(count):
            if not available_images:
                break

            # Cycle through available images if needed
            source_image = available_images[i % len(available_images)]

            filename = f"placeholder_{offset + i + 1}.jpg"
            filepath = output_dir / filename

            try:
                shutil.copy2(source_image, filepath)
                self._process_image(filepath)

                images.append(ImageSource(
                    url=str(source_image),
                    local_path=filepath,
                    source_type='placeholder',
                    alt_text=f"Image {offset + i + 1}"
                ))
            except Exception as e:
                logger.warning(f"Failed to copy placeholder image: {e}")

        return images

    def _extract_instagram_username(self, url: str) -> Optional[str]:
        """Extracts Instagram username from URL."""
        if not url:
            return None

        # Handle direct username
        if not url.startswith('http'):
            return url.lstrip('@')

        # Parse URL
        try:
            parsed = urlparse(url)
            path = parsed.path.strip('/')

            # Remove trailing slashes and get first path component
            username = path.split('/')[0]

            if username:
                return username
        except Exception:
            pass

        return None

    def _process_image(self, filepath: Path, max_size: int = 1200):
        """
        Processes image: converts to JPG, resizes if needed.
        """
        try:
            with Image.open(filepath) as img:
                # Convert to RGB if needed
                if img.mode in ('RGBA', 'P'):
                    img = img.convert('RGB')

                # Resize if too large
                if max(img.size) > max_size:
                    img.thumbnail((max_size, max_size), Image.Resampling.LANCZOS)

                # Save as JPG
                img.save(filepath, 'JPEG', quality=85)
        except Exception as e:
            logger.warning(f"Image processing failed for {filepath}: {e}")

    def close(self):
        """Cleanup resources."""
        self.session.close()


