def load_leads_from_excel(excel_path: Path) -> List[Lead]:
    """
    Reads Excel file and returns list of leads to process.
    Filters for Tier 1 leads that haven't been processed yet.
    """
    try:
        df = pd.read_excel(excel_path, engine='openpyxl')

        # Standardize column names (handle variations)
        column_mapping = {
            'Business Name': 'business_name',
            'Niche': 'niche',
            'País': 'pais',
            'Región': 'region',
            'Ciudad': 'ciudad',
            'Comuna': 'comuna',
            'Website URL': 'website_url',
            'Phone/WhatsApp': 'phone_whatsapp',
            'Instagram/FB Link': 'instagram_fb_link',
            'Status': 'status',
            'Tech Flaw': 'tech_flaw',
            'Owner Name': 'owner_name',
            'Tier': 'tier',
            'Source Query': 'source_query',
            'Generate Mockup': 'generate_mockup',
            'Mockup Status': 'mockup_status',
            'Mockup Path': 'mockup_path',
            'Mockup Date': 'mockup_date',
        }

        # Rename columns that exist
        df = df.rename(columns={k: v for k, v in column_mapping.items() if k in df.columns})

        # Fill missing columns with empty strings
        for col in column_mapping.values():
            if col not in df.columns:
                df[col] = ''

        # Filter leads
        # 1. Tier 1 (no website)
        # 2. Generate Mockup = 'Yes' or empty
        # 3. Mockup Status is not 'Completed'

        mask = (
            (df['tier'].str.contains('Tier 1', case=False, na=False) | (df['tier'] == '')) &
            (df['generate_mockup'].str.lower().isin(['yes', 'si', 'sí', '']) | df['generate_mockup'].isna()) &
            (~df['mockup_status'].str.lower().isin(['completed', 'completado']))
        )

        filtered_df = df[mask].copy()

        leads = []
        for idx, row in filtered_df.iterrows():
            lead = Lead(
                business_name=str(row.get('business_name', '')).strip(),
                niche=str(row.get('niche', '')).strip(),
                pais=str(row.get('pais', 'Chile')).strip(),
                region=str(row.get('region', '')).strip(),
                ciudad=str(row.get('ciudad', '')).strip(),
                comuna=str(row.get('comuna', '')).strip(),
                website_url=str(row.get('website_url', '')).strip(),
                phone_whatsapp=str(row.get('phone_whatsapp', '')).strip(),
                instagram_fb_link=str(row.get('instagram_fb_link', '')).strip(),
                status=str(row.get('status', '')).strip(),
                tech_flaw=str(row.get('tech_flaw', '')).strip(),
                owner_name=str(row.get('owner_name', '')).strip(),
                tier=str(row.get('tier', '')).strip(),
                source_query=str(row.get('source_query', '')).strip(),
                generate_mockup=str(row.get('generate_mockup', '')).strip(),
                mockup_status=str(row.get('mockup_status', '')).strip(),
                mockup_path=str(row.get('mockup_path', '')).strip(),
                mockup_date=row.get('mockup_date') if pd.notna(row.get('mockup_date')) else None,
                row_index=idx
            )

            # Skip if no business name
            if lead.business_name:
                leads.append(lead)

        logger.info(f"Loaded {len(leads)} leads to process from Excel")
        return leads

    except Exception as e:
        logger.error(f"Failed to load Excel file: {e}")
        raise


def update_lead_status(
    excel_path: Path,
    row_index: int,
    status: str,
    mockup_path: Optional[str] = None,
    mockup_date: Optional[datetime] = None
):
    """
    Updates a single lead's status in the Excel file.
    """
    try:
        # Read with openpyxl to preserve formatting
        from openpyxl import load_workbook

        wb = load_workbook(excel_path)
        ws = wb.active

        # Find column indices (1-indexed)
        header_row = 1
        headers = {cell.value: cell.column for cell in ws[header_row]}

        # Excel row is index + 2 (1 for 0-indexing, 1 for header)
        excel_row = row_index + 2

        # Update Mockup Status
        if 'Mockup Status' in headers:
            ws.cell(row=excel_row, column=headers['Mockup Status'], value=status)

        # Update Mockup Path
        if mockup_path and 'Mockup Path' in headers:
            ws.cell(row=excel_row, column=headers['Mockup Path'], value=mockup_path)

        # Update Mockup Date
        if mockup_date and 'Mockup Date' in headers:
            ws.cell(row=excel_row, column=headers['Mockup Date'], value=mockup_date)

        wb.save(excel_path)
        logger.debug(f"Updated Excel row {excel_row}: status={status}")

    except Exception as e:
        logger.error(f"Failed to update Excel: {e}")


